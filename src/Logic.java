public class Logic {
    public static int add(int number1, int number2) throws ArithmeticException {
        return number1 + number2;
    }

    public static double addf(double number1, double number2) throws ArithmeticException {
        return number1 + number2;
    }

    public static int subtract(int number1, int number2)throws ArithmeticException {
        return number1 - number2;
    }

    public static double subtractf(double number1, double number2) throws ArithmeticException {
        return number1 - number2;
    }

    public static int multiply(int number1, int number2) throws ArithmeticException {
        return number1 * number2;
    }

    public static double multiplyf(double number1, double number2) throws ArithmeticException {
        return number1 * number2;
    }

    public static int divide(int number1, int number2) throws ArithmeticException {
        return number1 / number2;
    }

    public static double dividef(double number1, double number2) throws ArithmeticException {
        return number1 / number2;
    }
}

